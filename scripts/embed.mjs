// Embeds everything in public/ into src/static.generated.ts so the Worker serves it directly.
// Runs automatically before `wrangler dev` / `wrangler deploy` (see "build" in wrangler.jsonc).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const root = new URL('../public/', import.meta.url).pathname;
const TYPES = { '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.svg': 'image/svg+xml' };
const files = {};
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (TYPES[extname(p)]) files['/' + relative(root, p).split('\\').join('/')] = [readFileSync(p, 'utf8'), TYPES[extname(p)]];
  }
})(root);
if (files['/index.html']) files['/'] = files['/index.html'];
if (files['/admin.html']) files['/admin'] = files['/admin.html'];
writeFileSync(new URL('../src/static.generated.ts', import.meta.url),
  '// Generated by scripts/embed.mjs. Do not edit.\nexport const STATIC: Record<string, [string, string]> = ' + JSON.stringify(files) + ';\n');
console.log(`embedded ${Object.keys(files).length} paths`);
